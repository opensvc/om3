type (
	// registerReq structures the POST /register request body
	registerReq struct {
		Nodename string `json:"nodename"`
		App      string `json:"app,omitempty"`

		// ClusterID is the cluster id of the node, so the collector knows
		// it before the first daemon status. Only the oc3 collector reads
		// it.
		ClusterID string `json:"cluster_id,omitempty"`

		// UUID is the registration id a node joining the cluster held
		// before the join, for the node registering it.
		UUID string `json:"uuid,omitempty"`
	}

	// registerResOK structures the successful POST oc3 node register response body
	registerResOK struct {
		UUID string `json:"uuid"`
		Info string `json:"info"`
	}
)

// Register logs in to the collector using the provided user credentials.
//
// If the node is not already known to the collector, a new node uuid is
// generated by the collector and stored by the agent in the node config
// as a node.uuid key.
//
// The node registers on the oc3 server, by POST /api/auth/node: with the
// credentials of the user given, in the app given or the default one of the
// user, or anonymously, which the collector may refuse, in the app given,
// which oc3 requires.
//
// If app is not set, the node is added to any app under the user's
// responsibility.
func (t Node) Register(ctx context.Context, user, password, app string) error {
	if err := t.register(user, password, app); err != nil {
		return fmt.Errorf("register: %w", err)
	}
	return t.PushRegistered(ctx)
}

// PushRegistered sends the collector the initial inventory of a node just
// registered: asset, packages, disks, sysreport and checks. The collector
// then knows the node in details, and can serve it contextualized
// compliance rulesets, without waiting for the scheduled pushes.
//
// The asset, package and disk pushes are required, the sysreport and checks
// pushes are not supported by every collector yet.
func (t Node) PushRegistered(ctx context.Context) error {
	if _, err := t.PushAsset(); err != nil {
		return fmt.Errorf("push asset: %w", err)
	} else {
		t.Log().Infof("sent initial asset discovery")
	}
	if data, err := t.PushPkg(); err != nil {
		return fmt.Errorf("push pkg: %w", err)
	} else {
		t.Log().Infof("sent initial package inventory (%d)", len(data))
	}
	if _, err := t.PushDisks(); err != nil {
		return fmt.Errorf("push disk: %w", err)
	}
	t.Log().Infof("sent initial disk inventory")

	if err := t.Sysreport(); err != nil {
		// TODO: implement oc3 sysreport
		// return fmt.Errorf("sysreport: %w", err)
		t.Log().Warnf("sysreport: %s", err)
	} else {
		t.Log().Infof("sent initial sysreport")
	}

	if data, err := t.Checks(ctx); err != nil {
		// TODO: implement oc3 push check
		// return fmt.Errorf("push check: %w", err)
		t.Log().Warnf("push check: %s", err)
	} else {
		t.Log().Infof("sent initial checks (%d)", data.Len())
	}
	return nil
}

func (t Node) register(user, password, app string) error {
	if !t.CollectorRawConfig().HasServerV3() {
		// The former collector is no longer fed: om registers on oc3.
		return fmt.Errorf("no oc3 collector to register on: set collector.url, or collector.server")
	}
	if user == "" {
		return t.registerAnonymousV3(app)
	} else {
		return t.registerAsUserV3(user, password, app)
	}
}

func (t Node) registerAsUserV3(user, password, app string) error {
	var (
		req  *http.Request
		resp *http.Response

		ioReader io.Reader

		method = http.MethodPost
		path   = oc3path.ServerRegister
	)
	if app == "" {
		app = t.MergedConfig().GetString(key.Parse("node.app"))
	}
	if password == "" {
		fmt.Printf("Password: ")
		if b, err := term.ReadPassword(int(os.Stdin.Fd())); err != nil {
			return err
		} else {
			password = string(b)
			fmt.Println("")
		}
	}
	auth := "Basic " + base64.StdEncoding.EncodeToString([]byte(user+":"+password))
	oc3, err := t.CollectorServerWithAuth(auth)
	if err != nil {
		return fmt.Errorf("create collector server: %w", err)
	}
	reqData := registerReq{
		Nodename:  hostname.Hostname(),
		App:       app,
		ClusterID: t.clusterID(),
	}
	if b, err := json.Marshal(reqData); err != nil {
		return fmt.Errorf("encode request body:%w", err)
	} else {
		ioReader = bytes.NewBuffer(b)
	}

	ctx, cancel, timeout := t.collectorRequestContext(context.Background())
	defer cancel()

	req, err = oc3.NewRequestWithContext(ctx, method, path, ioReader)
	if err != nil {
		return fmt.Errorf("create collector request %s %s: %w", method, path, err)
	}

	resp, err = oc3.Do(req)
	if err != nil {
		return collectorRequestError(err, method, path, timeout)
	}
	defer func() { _ = resp.Body.Close() }()

	if err := CollectorResponseStatusCheck(resp, method, path, []int{http.StatusOK}); err != nil {
		return err
	}
	dec := json.NewDecoder(resp.Body)
	data := registerResOK{}
	if err := dec.Decode(&data); err != nil {
		return fmt.Errorf("decode response body: %w", err)
	}
	if data.Info != "" {
		t.Log().Infof("%s", data.Info)
	}
	return t.writeUUID(data.UUID)
}

// RegisterJoiningNode registers on the collector the node nodename joining
// the cluster, authenticated by this node registration id, and returns the
// new registration id of the joining node.
//
// prevUUID is the registration id the joining node held before the join:
// the collector only registers a joining node already registered under its
// nodename, and moves it to the app and the cluster of this node.
func (t *Node) RegisterJoiningNode(ctx context.Context, nodename, prevUUID string) (string, error) {
	var (
		method = http.MethodPost
		path   = oc3path.ServerRegister
	)
	oc3, err := t.CollectorServer()
	if err != nil {
		return "", fmt.Errorf("create collector server: %w", err)
	}
	b, err := json.Marshal(registerReq{Nodename: nodename, UUID: prevUUID})
	if err != nil {
		return "", fmt.Errorf("encode request body: %w", err)
	}

	ctx, cancel, timeout := t.collectorRequestContext(ctx)
	defer cancel()

	req, err := oc3.NewRequestWithContext(ctx, method, path, bytes.NewBuffer(b))
	if err != nil {
		return "", fmt.Errorf("create collector request %s %s: %w", method, path, err)
	}
	resp, err := oc3.Do(req)
	if err != nil {
		return "", collectorRequestError(err, method, path, timeout)
	}
	defer func() { _ = resp.Body.Close() }()

	if err := CollectorResponseStatusCheck(resp, method, path, []int{http.StatusOK}); err != nil {
		return "", err
	}
	data := registerResOK{}
	if err := json.NewDecoder(resp.Body).Decode(&data); err != nil {
		return "", fmt.Errorf("decode response body: %w", err)
	}
	if data.UUID == "" {
		return "", fmt.Errorf("collector %s %s: empty uuid in response", method, path)
	}
	return data.UUID, nil
}

// clusterID returns the cluster id of the node, empty when it has none.
func (t Node) clusterID() string {
	v, _ := t.MergedConfig().Eval(key.T{Section: "cluster", Option: "id"})
	s, _ := v.(string)
	return s
}

// registerAnonymousV3 registers the node on oc3 with no credentials. The
// collector refuses it unless it allows anonymous registrations, and refuses
// it for a node already registered: its uuid is the password of the node.
func (t Node) registerAnonymousV3(app string) error {
	var (
		method = http.MethodPost
		path   = oc3path.ServerRegister
	)
	if app == "" {
		app = t.MergedConfig().GetString(key.Parse("node.app"))
	}
	oc3, err := t.CollectorServerWithoutAuth()
	if err != nil {
		return fmt.Errorf("create collector server: %w", err)
	}
	b, err := json.Marshal(registerReq{
		Nodename:  hostname.Hostname(),
		App:       app,
		ClusterID: t.clusterID(),
	})
	if err != nil {
		return fmt.Errorf("encode request body: %w", err)
	}

	ctx, cancel, timeout := t.collectorRequestContext(context.Background())
	defer cancel()

	req, err := oc3.NewRequestWithContext(ctx, method, path, bytes.NewBuffer(b))
	if err != nil {
		return fmt.Errorf("create collector request %s %s: %w", method, path, err)
	}
	resp, err := oc3.Do(req)
	if err != nil {
		return collectorRequestError(err, method, path, timeout)
	}
	defer func() { _ = resp.Body.Close() }()

	if err := CollectorResponseStatusCheck(resp, method, path, []int{http.StatusOK}); err != nil {
		switch resp.StatusCode {
		case http.StatusUnauthorized, http.StatusForbidden:
			return fmt.Errorf("%w: the collector accepts no anonymous registration: register with the credentials of a collector user, with --user", err)
		case http.StatusBadRequest:
			return fmt.Errorf("%w: give the app with --app, or register with the credentials of a collector user, with --user", err)
		case http.StatusConflict:
			return fmt.Errorf("%w: register with the credentials of a collector user, with --user", err)
		}
		return err
	}
	data := registerResOK{}
	if err := json.NewDecoder(resp.Body).Decode(&data); err != nil {
		return fmt.Errorf("decode response body: %w", err)
	}
	if data.Info != "" {
		t.Log().Infof("%s", data.Info)
	}
	return t.writeUUID(data.UUID)
}

func (t Node) writeUUID(s string) error {
	if current := t.Config().GetString(key.Parse("node.uuid")); current == s {
		return nil
	}
	op := keyop.Parse("node.uuid=" + s)
	return t.Config().Set(*op)
}
